def _summarize_nb_params(params):
    summary = {}
    for param_name, values in params.items():
        _values = np.asarray(values, dtype=np.float64)
        summary[param_name] = np.array(
            [
                _values.sum(),
                _values.mean(),
                _values.min(),
                _values.max(),
                _values[0],
                _values[-1],
            ]
        )
    return summary


def _read_gromacs_section(file_path, section_name):
    rows = []
    in_section = False
    with open(file_path) as file:
        for raw_line in file:
            line = raw_line.strip()
            if line.startswith("[") and "]" in line:
                in_section = line.split("]", maxsplit=1)[0].strip("[]").strip() == section_name
                continue
            if not in_section or not line or line.startswith(";"):
                continue
            rows.append(line.split(";", maxsplit=1)[0].split())
    return rows


def _summarize_itp_values(values):
    values = np.array(values, dtype=np.float64)
    if values.size == 0:
        return np.zeros(len(_ITP_FF_SUMMARY_KEYS), dtype=np.float64)
    return np.array([values.size, values.sum(), values.min(), values.max(), values[0]], dtype=np.float64)


def _summarize_itp_force_field_params(itp_path):
    bonds = _read_gromacs_section(itp_path, "bonds")
    angles = _read_gromacs_section(itp_path, "angles")
    dihedrals = _read_gromacs_section(itp_path, "dihedrals")
    proper_dihedrals = [row for row in dihedrals if row[4] == "9"]
    improper_dihedrals = [row for row in dihedrals if row[4] == "4"]
    pairs = _read_gromacs_section(itp_path, "pairs")

    return {
        "bonds_r": _summarize_itp_values([row[3] for row in bonds]),
        "bonds_k": _summarize_itp_values([row[4] for row in bonds]),
        "angles_theta": _summarize_itp_values([row[4] for row in angles]),
        "angles_k": _summarize_itp_values([row[5] for row in angles]),
        "proper_phase": _summarize_itp_values([row[5] for row in proper_dihedrals]),
        "proper_k": _summarize_itp_values([row[6] for row in proper_dihedrals]),
        "improper_phase": _summarize_itp_values([row[5] for row in improper_dihedrals]),
        "improper_k": _summarize_itp_values([row[6] for row in improper_dihedrals]),
        "pairs": np.array([len(pairs)], dtype=np.float64),
    }


def _assert_written_param_files(mol_name, mol, metadata, params, tfs, out_dir):
    itp_path = out_dir / f"{mol_name}.itp"
    json_path = out_dir / f"{mol_name}.json"
    nb_params_path = out_dir / f"{mol_name}_nb_params.json"

    tfs.write_itp(str(itp_path), separated_atp=True)
    atp_path = itp_path.with_suffix(".atp")
    with open(json_path, "w") as file:
        json.dump(params, file, indent=2)
    with open(nb_params_path, "w") as file:
        json.dump({"metadata": metadata}, file, indent=2)

    for file_path in [itp_path, atp_path, json_path, nb_params_path]:
        assert file_path.is_file(), file_path
        assert file_path.stat().st_size > 0, file_path

    atoms = _read_gromacs_section(itp_path, "atoms")
    assert len(atoms) == mol.natoms
    assert [int(row[0]) for row in atoms] == list(range(1, mol.natoms + 1))
    assert [row[3] for row in atoms] == ["UNL"] * mol.natoms

    itp_atom_types = [row[1] for row in atoms]
    itp_charges = np.array([float(row[6]) for row in atoms], dtype=np.float64)
    itp_masses = np.array([float(row[7]) for row in atoms], dtype=np.float64)
    params_charges = np.array(params["charge"], dtype=np.float64)
    assert np.allclose(itp_charges[:-1], params_charges[:-1], atol=1e-5, rtol=0.0)
    # The ITP writer stores charges with five decimals and compensates the final
    # atom so the written molecule has the exact integer net charge.
    assert np.isclose(itp_charges.sum(), round(params_charges.sum()), atol=1e-8, rtol=0.0)
    assert np.isclose(itp_charges[-1], round(params_charges.sum()) - itp_charges[:-1].sum(), atol=1e-8, rtol=0.0)
    assert np.all(itp_masses > 0.0)

    atomtypes = _read_gromacs_section(atp_path, "atomtypes")
    assert len(atomtypes) == mol.natoms
    assert [row[0] for row in atomtypes] == itp_atom_types
    assert [int(row[1]) for row in atomtypes] == list(mol.atomic_numbers)
    assert np.allclose([float(row[-2]) for row in atomtypes], 0.0, atol=0.0)
    assert np.allclose([float(row[-1]) for row in atomtypes], 0.0, atol=0.0)

    with open(json_path) as file:
        loaded_params = json.load(file)
    assert set(loaded_params) == set(params)
    for param_name, values in params.items():
        assert np.allclose(
            np.array(loaded_params[param_name], dtype=np.float64),
            np.array(values, dtype=np.float64),
            rtol=0.0,
            atol=0.0,
        )

    with open(nb_params_path) as file:
        assert json.load(file) == {"metadata": metadata}

    return _summarize_itp_force_field_params(itp_path)


