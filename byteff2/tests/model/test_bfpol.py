def _predict_cluster_pes_ff_energies(model, cluster_name):
    cluster_dir = os.path.join(_CLUSTER_PES_DATA_DIR, cluster_name)
    files = sorted(glob(os.path.join(cluster_dir, "*.xyz")))
    mols = [Molecule(fp) for fp in files]
    coords = np.concatenate([np.array(mol.get_confdata("coords")) for mol in mols], axis=1)
    data = ClusterData(
        "test", [mol.get_mapped_smiles() for mol in mols], confdata={"coords": coords}, max_n_confs=mols[0].nconfs
    )
    data = collate_data([data])

    with torch.no_grad():
        preds = model(data, cluster=True)
    return (preds["energy_cluster"].sum(dim=0) - preds["energy"].sum(dim=0)).detach().cpu()


def _predict_dimer_separated_ff_energies(model, dimer_name):
    dimer_dir = os.path.join(_DIMER_DATA_DIR, dimer_name)
    names = dimer_name.split("_")[:2]
    mols = [Molecule(os.path.join(dimer_dir, f"{name}_{i}.xyz")) for i, name in enumerate(names)]
