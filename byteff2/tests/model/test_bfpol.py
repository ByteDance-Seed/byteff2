def test_trained_model_dimer_separated_energy_predictions():
    trained_model.to(device_)
    for dimer_name, expected_terms in _EXPECTED_DIMER_SEPARATED_FF_ENERGIES.items():
        pred_terms = _predict_dimer_separated_ff_energies(trained_model, dimer_name)
        for term, expected in expected_terms.items():
            pred = pred_terms[term]
            target = torch.tensor(expected, dtype=pred.dtype)
            assert pred.shape == target.shape
            assert torch.allclose(pred, target, atol=1e-3), (
                dimer_name,
                term,
                (pred - target).abs().max().item(),
            )

        separated_total = sum(pred_terms[term] for term in ["POLARIZATION", "ELEC", "PAULI", "DISP", "CHARGE_TRANSFER"])
        assert torch.allclose(pred_terms["TOTAL"], separated_total, atol=1e-3), (
            dimer_name,
            (pred_terms["TOTAL"] - separated_total).abs().max().item(),
        )


def test_trained_model_bamboo_nb_param_predictions(tmp_path):
    # check force field parameter prediction

    trained_model.to(device_)
    expected_metadata = {
        "exp6": True,
        "s12": 0.1690015023721859,
        "disp_damping": 120.0,
        "thole": 0.39,
    }

    for mol_name, expected_summary in _EXPECTED_BAMBOO_NB_PARAM_SUMMARIES.items():
        mol = Molecule.from_mapped_smiles(bamboo_name_mapped_smiles[mol_name], nconfs=1)
        mol.name = mol_name
        metadata, params, tfs, returned_mol = get_nb_params(trained_model, mol, write_to_itp=True)

        assert returned_mol is mol
        assert mol.natoms == expected_summary["natoms"]
        assert metadata == expected_metadata
        assert tfs is not None
        itp_summary = _assert_written_param_files(mol_name, mol, metadata, params, tfs, tmp_path)

        for section_name, expected_values in _EXPECTED_BAMBOO_ITP_FF_SUMMARIES[mol_name].items():
            _expected_values = np.array(expected_values, dtype=np.float64)
            assert itp_summary[section_name].shape == _expected_values.shape
            assert np.allclose(itp_summary[section_name], _expected_values, atol=1e-4), (
                mol_name,
                section_name,
                itp_summary[section_name].tolist(),
            )

        assert set(params) == set(expected_summary) - {"natoms"}
        for param_name, param_values in params.items():
            assert len(param_values) == mol.natoms
            assert np.all(np.isfinite(param_values))

        summary = _summarize_nb_params(params)
        for param_name, expected_values in expected_summary.items():
            if param_name == "natoms":
                continue
            _expected_values = np.array(expected_values, dtype=np.float64)
            assert summary[param_name].shape == _expected_values.shape == (len(_PARAM_SUMMARY_KEYS),)
            assert np.allclose(summary[param_name], _expected_values, atol=1e-4), (
                mol_name,
                param_name,
                dict(zip(_PARAM_SUMMARY_KEYS, np.abs(summary[param_name] - _expected_values).tolist())),
            )
